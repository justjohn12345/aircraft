"""
Makes an instrumented copy of a generated model (never the repo's model/ folder) for the control-law checks:
- FmgcComputer.cpp: the calls to the outer loops go through fmgcLabOuterLoopsStep/Reset (src/lab_hooks.h), which
  capture every input and output of FmgcOuterLoops::step and notify the checker;
- FmgcOuterLoops.cpp: probe statements `fmgcLabProbe("name", expr);` inserted before given lines (probe files).
Also writes outer_io.gen.h: unpacks the captured step() arguments into an ap_laws_output, by parameter name.

Usage: gen_hooked_model.py <model_dir> <out_dir> <probe files...>
"""
import os
import re
import sys


def main():
    model, out = sys.argv[1], sys.argv[2]
    probes = {}
    for pf in sys.argv[3:]:
        for line in open(pf):
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            kw, ln, name, expr = line.split(None, 3)
            assert kw == 'BEFORE', line
            expr = re.sub(r'\bP\.', 'FmgcOuterLoops_rtP.', expr)
            probes.setdefault(int(ln), []).append(f'  fmgcLabProbe("{name}", ({expr}));')
    os.makedirs(out, exist_ok=True)

    src = open(os.path.join(model, 'FmgcComputer.cpp')).read()
    n1 = src.count('LawMDLOBJ1.step(')
    n2 = src.count('LawMDLOBJ1.reset();')
    assert n1 == 1 and n2 == 1, (n1, n2)
    src = src.replace('LawMDLOBJ1.step(', 'fmgcLabOuterLoopsStep(LawMDLOBJ1, ')
    src = src.replace('LawMDLOBJ1.reset();', 'fmgcLabOuterLoopsReset(LawMDLOBJ1);')
    src = '#include "lab_hooks.h"\n' + src
    open(os.path.join(out, 'FmgcComputer.cpp'), 'w').write(src)

    lines = open(os.path.join(model, 'FmgcOuterLoops.cpp')).read().split('\n')
    outl = ['#include "lab_hooks.h"']
    for i, l in enumerate(lines, 1):
        outl.extend(probes.get(i, []))
        outl.append(l)
    open(os.path.join(out, 'FmgcOuterLoops.cpp'), 'w').write('\n'.join(outl))

    # step() signature -> parameter names in order
    text = '\n'.join(lines)
    m = re.search(r'void FmgcOuterLoops::step\((.*?)\)\s*\{', text, re.S)
    params = [p.strip() for p in m.group(1).replace('\n', ' ').split(',')]
    ins, outs = [], []
    for pos, p in enumerate(params):
        name = re.search(r'(\w+)$', p).group(1)
        is_bool = 'boolean_T' in p
        (ins if p.startswith('const') else outs).append((pos, name, is_bool))

    def field(name):
        for pre, path in (('rtu_in_time_', 'time.'), ('rtu_in_data_', 'data.'), ('rtu_in_input_', 'input.'),
                          ('rty_out_flight_director_', 'output.flight_director.'),
                          ('rty_out_autopilot_', 'output.autopilot.'), ('rty_out_flare_law_', 'output.flare_law.'),
                          ('rty_out_', 'output.')):
            if name.startswith(pre):
                return path + name[len(pre):]
        raise SystemExit('unmapped parameter ' + name)

    g = ['// Generated by gen_hooked_model.py. Do not edit.', '#pragma once', '#include <vector>',
         '#include "FmgcOuterLoops_types.h"', '',
         '/** Captured FmgcOuterLoops::step() arguments before the call -> io.time/data/input. */',
         'inline void unpackOuterInputs(const std::vector<double>& v, ap_laws_output& io) {']
    for i, n, b in ins:
        g.append(f'  io.{field(n)} = {"v[%d] != 0" % i if b else "v[%d]" % i};')
    g += ['}', '', '/** Captured arguments after the call -> io.output. */',
          'inline void unpackOuterOutputs(const std::vector<double>& v, ap_laws_output& io) {']
    for i, n, b in outs:
        g.append(f'  io.{field(n)} = {"v[%d] != 0" % i if b else "v[%d]" % i};')
    g.append('}')
    open(os.path.join(out, 'outer_io.gen.h'), 'w').write('\n'.join(g) + '\n')


if __name__ == '__main__':
    main()
