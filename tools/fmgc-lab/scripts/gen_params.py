"""
Generates params.gen.h: a printer for every scalar and array member of a generated model's parameter struct
(`struct Parameters_<Model>_T { ... };` in <Model>.h). The parameter names keep the Simulink block names
(`ConfirmNode_timeDelay_xx`, `Logic_table_xx`, `ScheduledGain_Table`, ...), so the dump is the block dictionary.

Usage: gen_params.py <out.h> <Model>=<Model.h> [<Model>=<Model.h> ...]
"""
import re
import sys

PRINT = {
    'boolean_T': ('%d', 'static_cast<int>({})'),
    'real_T': ('%.17g', '{}'),
    'real32_T': ('%.9g', 'static_cast<double>({})'),
    'uint32_T': ('%u', 'static_cast<unsigned>({})'),
    'int32_T': ('%d', 'static_cast<int>({})'),
    'int8_T': ('%d', 'static_cast<int>({})'),
    'uint8_T': ('%u', 'static_cast<unsigned>({})'),
}


def members(header, model):
    text = open(header).read()
    m = re.search(r'struct Parameters_' + model + r'_T \{\n(.*?)\n  \};', text, re.S)
    if not m:
        raise SystemExit(f'no Parameters_{model}_T in {header}')
    out = []
    for line in m.group(1).splitlines():
        fm = re.match(r'\s*(\w+)\s+(\w+)((?:\[\d+\])*);', line)
        if not fm:
            raise SystemExit(f'cannot parse parameter member: {line!r}')
        dims = [int(d) for d in re.findall(r'\[(\d+)\]', fm.group(3))]
        out.append((fm.group(1), fm.group(2), dims))
    return out


def emit_model(model, var, mems):
    lines = [f'inline void dumpParams_{model}(std::FILE* f, const {model}::Parameters_{model}_T& p) {{']
    for type_, name, dims in mems:
        count = 1
        for d in dims:
            count *= d
        if type_ in PRINT:
            fmt, cast = PRINT[type_]
        else:
            # enums (fmgc_flight_phase, ...) and SignStatusMatrix print as int; struct defaults are skipped
            if type_[0].islower() and type_ not in ('ap_raw_output', 'fmgc_outputs', 'fcu_outputs', 'athr_output',
                                                  'athr_data_computed') and not type_.startswith('base_'):
                fmt, cast = '%d', 'static_cast<int>({})'
            else:
                lines.append(f'  std::fprintf(f, "{name} = <{type_}>\\n");')
                continue
        if not dims:
            lines.append(f'  std::fprintf(f, "{name} = {fmt}\\n", {cast.format("p." + name)});')
        else:
            flat = f'reinterpret_cast<const {type_}*>(&p.{name})'
            dimstr = 'x'.join(str(d) for d in dims)
            lines.append(f'  std::fprintf(f, "{name}[{dimstr}] =");')
            lines.append(f'  for (int i = 0; i < {count}; i++) std::fprintf(f, " {fmt}", {cast.format(flat + "[i]")});')
            lines.append('  std::fprintf(f, "\\n");')
    lines.append('}')
    lines.append('')
    lines.append(f'template <typename F> void forEachLogicTable_{model}(const {model}::Parameters_{model}_T& p, F f) {{')
    for type_, name, dims in mems:
        if name.startswith('Logic_table') and dims == [16]:
            lines.append(f'  f("{name}", p.{name});')
    lines.append('}')
    return '\n'.join(lines)


def main():
    out = sys.argv[1]
    parts = ['// Generated by gen_params.py. Do not edit.', '#pragma once', '#include <cstdio>', '']
    for arg in sys.argv[2:]:
        model, header = arg.split('=', 1)
        parts.append(emit_model(model, None, members(header, model)))
        parts.append('')
    open(out, 'w').write('\n'.join(parts) + '\n')


if __name__ == '__main__':
    main()
