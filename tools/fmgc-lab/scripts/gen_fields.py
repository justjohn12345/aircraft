"""
Generates fields.gen.h: a visitor over every scalar field of the generated FMGC structs, so the harness can compare,
print and mutate them by name. Parses the Simulink-generated *_types.h (simple `struct X { type name; };` and
`enum class X : int32_T { ... };` definitions).

Usage: gen_fields.py <FmgcComputer_types.h> <out.h>
       gen_fields.py <Model_types.h> <out.h> <root,root,...>   (e.g. FcuComputer_types.h fcu_fields.gen.h fcu_outputs)
"""
import re
import sys

SCALARS = {
    'boolean_T': 'bool',
    'real_T': 'double',
    'real32_T': 'float',
    'uint32_T': 'uint32',
    'int32_T': 'int32',
    'int8_T': 'int8',
    'uint8_T': 'uint8',
}

ROOTS = [
    'fmgc_inputs',
    'base_fmgc_logic_outputs',
    'base_fmgc_ap_fd_logic_outputs',
    'ap_raw_output',
    'base_fmgc_athr_outputs',
    'base_fmgc_discrete_outputs',
    'base_fmgc_bus_outputs',
    'base_fmgc_bus_inputs',
    'base_fmgc_discrete_inputs',
    'base_fms_inputs',
]


def parse(text):
    structs = {}
    enums = set()
    for m in re.finditer(r'enum class (\w+)\s*:\s*\w+\s*{', text):
        enums.add(m.group(1))
    for m in re.finditer(r'struct (\w+)\s*\n{\n(.*?)\n};', text, re.S):
        members = []
        for line in m.group(2).splitlines():
            fm = re.match(r'\s*(\w+)\s+(\w+)(\[(\d+)\])?;', line)
            if not fm:
                raise SystemExit(f'cannot parse member in {m.group(1)}: {line!r}')
            members.append((fm.group(1), fm.group(2), int(fm.group(4)) if fm.group(4) else None))
        structs[m.group(1)] = members
    return structs, enums


def emit(structs, enums, header='FmgcComputer_types.h'):
    out = [
        f'// Generated by gen_fields.py from {header}. Do not edit.',
        '#pragma once',
        f'#include "{header}"',
        '',
        '// V must provide: template <typename T> void field(const char* prefix, const char* name, T& a, T& b, FieldKind kind);',
        'enum class FieldKind { Bool, Float, Int, Enum };',
        '',
    ]
    # forward declarations
    for s in structs:
        out.append(f'template <typename V> void visit(V& v, const char* prefix, {s}& a, {s}& b);')
    out.append('')
    for s, members in structs.items():
        out.append(f'template <typename V> void visit(V& v, const char* prefix, {s}& a, {s}& b) {{')
        for type_, name, count in members:
            if count is not None:
                raise SystemExit(f'arrays not supported: {s}.{name}')
            if type_ in structs:
                out.append(f'  {{ std::string p = std::string(prefix) + "{name}."; visit(v, p.c_str(), a.{name}, b.{name}); }}')
            elif type_ in SCALARS:
                kind = {'bool': 'Bool', 'double': 'Float', 'float': 'Float'}.get(SCALARS[type_], 'Int')
                out.append(f'  v.field(prefix, "{name}", a.{name}, b.{name}, FieldKind::{kind});')
            elif type_ in enums:
                out.append(f'  v.field(prefix, "{name}", a.{name}, b.{name}, FieldKind::Enum);')
            else:
                raise SystemExit(f'unknown type {type_} in {s}.{name}')
        out.append('}')
        out.append('')
    return '\n'.join(out) + '\n'


def main():
    text = open(sys.argv[1]).read()
    structs, enums = parse(text)
    roots = sys.argv[3].split(',') if len(sys.argv) > 3 else ROOTS
    missing = [r for r in roots if r not in structs]
    if missing:
        raise SystemExit(f'missing root structs: {missing}')
    header = sys.argv[1].replace('\\', '/').split('/')[-1]
    code = emit(structs, enums, header)
    open(sys.argv[2], 'w').write('#include <string>\n' + code)


if __name__ == '__main__':
    main()
